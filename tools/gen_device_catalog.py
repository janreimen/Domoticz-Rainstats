#!/usr/bin/env python3
"""Generate docs/DEVICES.md from the device model and the round-robin layout in rain_stats/constants.py.

    python3 tools/gen_device_catalog.py          write docs/DEVICES.md
    python3 tools/gen_device_catalog.py --check  exit 1 when docs/DEVICES.md is stale (the test suite does the same)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from rain_stats import constants as c  # noqa: E402

TARGET = os.path.join(ROOT, "docs", "DEVICES.md")

# where each device gets its value from
SOURCES = {
    "status": "the connection: On while the rain device can be read, Off while it cannot",
    "info": "the plugin: last reading, rain rate, since when data are collected, partial windows",
}
for _window in c.WINDOWS:
    SOURCES["rain_" + _window.key] = "the rain of the last %s (see *The windows*)" % _window.label
    SOURCES["peak_" + _window.key] = "largest rain rate in the last %s" % _window.label

WINDOW_OF = {w.key: w for w in c.WINDOWS}

TYPES = {
    c.KIND_RAIN: "Custom Sensor (mm, one decimal)",
    c.KIND_RATE: "Custom Sensor (mm/h, two decimals)",
    c.KIND_FLAG: "Switch (On/Off), read-only",
    c.KIND_TEXT: "Text, read-only",
}


def _duration(seconds, hours_only=False):
    """3600 -> "1 h", 86100 -> "23 h 55 min" (hours_only), 1209600 -> "14 d", 1206000 -> "13 d 23 h"."""
    days, rest = divmod(int(seconds), c.DAY)
    if hours_only:
        days, rest = 0, int(seconds)
    hours, rest = divmod(rest, 3600)
    minutes = rest // 60
    parts = []
    for value, unit in ((days, "d"), (hours, "h"), (minutes, "min")):
        if value:
            parts.append("%d %s" % (value, unit))
    return " ".join(parts) or "0 min"


def _units(devices):
    """[1, 2, 3, 4, 5, 6, 7, 8, 19, 20] -> "1-8 and 19-20"."""
    units = sorted(d.unit for d in devices)
    runs, start = [], 0
    for i in range(1, len(units) + 1):
        if i == len(units) or units[i] != units[i - 1] + 1:
            first, last = units[start], units[i - 1]
            runs.append(str(first) if first == last else "%d-%d" % (first, last))
            start = i
    return " and ".join(runs)


def _table(devices):
    """The devices, by unit. A device of a window says which line of .env switches it on or off."""
    out = ["| Unit | Name | Type | Unit label | Source | Created when |", "|---:|---|---|---|---|---|"]
    for spec in sorted(devices, key=lambda d: d.unit):
        window = WINDOW_OF.get(spec.window)
        created = "always" if window is None else "`%s=Y` (%s by default)" % (window.env_key, "Y" if window.default else "N")
        out.append("| %d | %s | %s | %s | %s | %s |" % (spec.unit, spec.name, TYPES[spec.kind], spec.label or "-",
                                                         SOURCES[spec.key], created))
    return out


def _windows_table():
    out = ["| Window | Tier (slot) | Slots | Rain covers | Peak rate covers | Devices | `.env` line | Default |",
           "|---|---|---:|---|---|---|---|---|"]
    rain = {d.window: d for d in c.RAIN_DEVICES}
    peak = {d.window: d for d in c.PEAK_DEVICES}
    for window in c.WINDOWS:
        tier = c.tier_of(window.tier)
        slots = c.window_slots(window)
        low = (slots - 1) * tier.resolution
        fine = window.tier == c.FINE                    # the windows of the fine ring are shown in hours
        out.append("| %s | %s (%s) | %d | the last %s | %s to %s | units %d and %d | `%s` | %s |" % (
            window.label, tier.key, _duration(tier.resolution), slots, window.label, _duration(low, fine), window.label,
            rain[window.key].unit, peak[window.key].unit, window.env_key, "Y" if window.default else "N"))
    return out


def _tiers_table():
    out = ["| Tier | Slot | Slots | Remembers | Answers |", "|---|---|---:|---|---|"]
    for tier in c.TIERS:
        answers = ", ".join(w.label for w in c.WINDOWS if w.tier == tier.key)
        out.append("| %s | %s | %d | %s | %s |" % (tier.key, _duration(tier.resolution), tier.slots,
                                                   _duration(tier.resolution * tier.slots), answers))
    return out


def render():
    out = [
        "# Devices",
        "",
        "<!-- Generated by tools/gen_device_catalog.py from rain_stats/constants.py. Do not edit by hand: "
        "run the tool. -->",
        "",
        "The plugin creates the devices below. No unit number ever changes and no unit is ever reused, so an upgrade "
        "keeps every device, its history, scenes, scripts and schedules.",
        "",
        "**Which windows get devices is your choice.** In the file `.env` beside `plugin.py` there is one line per "
        "window, `RS_LAST_001_DAYS=Y` ... `RS_LAST_365_DAYS=N`: `Y` creates the rain device of that window and its peak "
        "rain rate device, `N` creates neither. Without a `.env`, or without the line, the default of the table below "
        "is in force. A device that exists already is never deleted by the plugin: when you set `N` it stays where it "
        "is and is no longer updated (delete it in Domoticz when you do not want it any more). At least one window "
        "must be `Y`. Changes take effect when the hardware is restarted.",
        "",
        "Every chosen device is created when missing (at start and at every poll) and *in use* from the start, so "
        "nothing has to be added by hand under Setup > Devices. All devices are read-only: a command sent to one is "
        "answered by writing its real value back.",
        "",
        "## Rain (units %s)" % _units(c.RAIN_DEVICES),
        "",
        "The rain that fell in each window, in mm.",
        "",
    ]
    out += _table(c.RAIN_DEVICES)
    out += [
        "",
        "## Peak rain rate (units %s)" % _units(c.PEAK_DEVICES),
        "",
        "The highest rain rate that was seen in each window, in mm/h. Created unless the setting *Statistics* is "
        "*Rain only*; with that setting they are neither created nor updated (devices that already exist stay and "
        "keep their last value: delete them by hand).",
        "",
    ]
    out += _table(c.PEAK_DEVICES)
    out += [
        "",
        "## Status (units %d-%d)" % (c.UNIT_STATUS, c.UNIT_INFO),
        "",
    ]
    out += _table(c.FIXED_DEVICES)
    out += [
        "",
        "- **Rain Stats Status** follows the source: On while the rain device can be read, Off while it cannot. The "
        "statistics themselves never change because of a failed read: the windows keep sliding with the clock.",
        "- **Rain Stats Info** is a short text, for example `OK 08:34: 0.0 mm/h; collecting since 2026-11-18 00:00; "
        "windows from 1d on are partial` or `Source not reachable since 08:12: the statistics go on from the stored "
        "data`. With an imported history it also says `history from 2025-11-21` and, when the rain windows are "
        "complete but the peak rates are not, `peaks from 1d on are partial`.",
        "",
        "## The windows",
        "",
        "Rain is stored in a round-robin archive: fixed rings of equally long time slots, reused in a circle. Nothing "
        "grows and nothing is trimmed; the slot that becomes too old is overwritten by the one that takes its place. "
        "Every reading is added to both tiers:",
        "",
    ]
    out += _tiers_table()
    out += [
        "",
        "The **rain** of a window is the last N hours or days: the slot that is running now, the slots before it that "
        "make up the window, and the part of the slot before those that still lies inside the period, in proportion "
        "(rain is taken to have fallen evenly within a slot; the rain rings keep one slot more than the table says, for "
        "that part). So a storm fades out of a window through one slot "
        "instead of dropping out in one step, and on average the window is neither too high nor too low. The "
        "**peak rate** cannot be taken in proportion: it is made of whole slots only, the running one plus the ones "
        "before it, so it covers between N-1 slots and N slots of real time and **never reaches further back than the "
        "name says**:",
        "",
    ]
    out += _windows_table()
    out += [
        "",
        "- The windows slide with the clock: they are recomputed at least every %d seconds and after every reading, "
        "so rain leaves a window while it is dry, without any new reading." % c.STATS_SECONDS,
        "- A window is **partial** while the plugin knows less time than the window is long. Its value is the rain "
        "(or the peak) of the time that is known, never an estimate of the rest. The rain is known from the start of "
        "collecting, or from the start of the imported daily history when there is one (`RS_HISTORY_IDX`); the peak "
        "rain rate only from the start of collecting, because the history has no rates. *Rain Stats Info* names the "
        "first partial window.",
        "- Values are written when they change and rewritten every %d seconds when they do not, so Domoticz' sensor "
        "time-out never marks a quiet sensor as dead." % c.REFRESH_SECONDS,
        "- Domoticz refuses new devices while *Setup > Settings > System > Accept new Hardware Devices* is off. The "
        "plugin says so once in the log and asks again every %d minutes, so the devices appear as soon as the "
        "setting is on, without restarting the hardware." % (c.CREATE_RETRY_SECONDS // 60),
        "- A name, a visibility or a unit label you set yourself in Domoticz is never overwritten; a sensor that was "
        "created without a unit label gets its unit at start.",
        "",
    ]
    return "\n".join(out)


def main(argv):
    text = render()
    if "--check" in argv:
        with open(TARGET, encoding="utf-8") as fh:
            if fh.read() != text:
                print("docs/DEVICES.md is stale: run python3 tools/gen_device_catalog.py", file=sys.stderr)
                return 1
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(TARGET, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
